<script>
document.addEventListener('DOMContentLoaded', function() {
    // Tabs functionality
    const caseTabs = document.querySelectorAll('[data-case-tab]');
    const caseContents = document.querySelectorAll('[data-case-content]');

    caseTabs.forEach(tab => {
        tab.addEventListener('click', function(e) {
            e.preventDefault();
            const targetId = this.getAttribute('href').substring(1);

            // Remove active class from all tabs and contents
            caseTabs.forEach(t => t.classList.remove('active'));
            caseContents.forEach(c => c.classList.remove('active'));

            // Add active class to clicked tab and corresponding content
            this.classList.add('active');
            document.getElementById(targetId).classList.add('active');

            // Reinitialize Swiper for the active tab
            const activeSlider = document.querySelector(`#${targetId} .cases-slider`);
            if (activeSlider && typeof Swiper !== 'undefined') {
                new Swiper(activeSlider, {
                    slidesPerView: 1,
                    spaceBetween: 16,
                    navigation: {
                        nextEl: '.cases-next',
                        prevEl: '.cases-prev',
                    },
                    breakpoints: {
                        640: {
                            slidesPerView: 2,
                            spaceBetween: 20,
                        },
                        1024: {
                            slidesPerView: 3,
                            spaceBetween: 24,
                        },
                    },
                });
            }
        });
    });

    // Initialize Swiper for the first active tab
    const firstActiveSlider = document.querySelector('.tab.active .cases-slider');
    if (firstActiveSlider && typeof Swiper !== 'undefined') {
        new Swiper(firstActiveSlider, {
            slidesPerView: 1,
            spaceBetween: 16,
            navigation: {
                nextEl: '.cases-next',
                prevEl: '.cases-prev',
            },
            breakpoints: {
                640: {
                    slidesPerView: 2,
                    spaceBetween: 20,
                },
                1024: {
                    slidesPerView: 3,
                    spaceBetween: 24,
                },
            },
        });
    }
});
</script>
